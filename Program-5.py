#Question : WAP to enter a temperature in fahrenheit and convert it into celsius.

#Answer :
F = float(input("Enter the temperature in fahrenheit: "))
C = ((F - 32) * 5) / 9
print("The value of fahrenheit in Celsius is:", C)

